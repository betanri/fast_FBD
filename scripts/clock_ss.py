#!/usr/bin/env python3
"""Clock-model comparison by marginal likelihood (stepping-stone and path sampling, RevBayes 1.3.2) on the 23-gene DNA of A06 and
A12 (user request, 12 Nov 2026: decide the clock for the final analyses). Full FBD with fossils is too slow for power posteriors
(one DNA chain takes 22-25 h for an ESS of 20-35), so the clock is compared on the fixed living-species time tree: node ages are
fixed at the posterior medians of a full-DNA FBD run, and only the substitution model (GTR+G4, as in tests 4a/4b) and the branch
rates are sampled. Two time trees are used, so neither clock is favoured by its own dates: RevBayes DNA (exponential clock) and
MrBayes DNA (IGR clock), both from test 4b (val4b/mbdna_SET.tsv). TIMES = free: node ages are sampled instead, under a
birth-death prior on the fixed extant topology (root fixed at the RevBayes DNA median), with each fossil-bearing clade's oldest
fossil as a hard minimum on its stem node (fossils are total-group in these sets), so the comparison integrates over time
uncertainty. Fossils themselves are not placed (that does not bear on which clock fits the DNA).

Clocks (rate per branch of the rooted extant tree; the two root branches share one unrooted edge, as in the DNA runs):
  strict  one rate                                         mean ~ Exponential(10), as in the DNA runs
  exp     rate ~ Exponential(mean)                          ffbd and the RevBayes DNA runs
  ln      rate ~ Lognormal(ln mean - s^2/2, s), s ~ Exponential(mean 0.587)          (uncorrelated lognormal)
  gam     rate ~ Gamma(k, k / mean), k ~ Exponential(1)                              (uncorrelated gamma; k = 1 is exp)
  igr     rate ~ Gamma(t / v, t / (v mean)), v ~ Exponential(10), t = branch time    (MrBayes IGR)
  acln    ln rate ~ Normal(ln parent rate - s^2 t / 2, s sqrt(t)), s ~ Exponential(10), root rate = mean   (autocorrelated)

  clock_ss.py SET CLOCK TIMES SEED OUT.Rev      TIMES = rb | mb | free; run from the analysis folder
"""
import csv, re, sys

S, CLOCK, TIMES, SEED, OUT = sys.argv[1:6]
D = f'fast_fbd_test/fish_root/data/{S}_root'
FREE = TIMES == 'free'
PROG = {'rb': 'RevBayes DNA (6 chains)', 'mb': 'MrBayes DNA', 'free': 'RevBayes DNA (6 chains)'}[TIMES]
age = {r['node']: float(r['median']) for r in csv.DictReader(open(f'val4b/mbdna_{S}.tsv'), delimiter='\t') if r['program'] == PROG}
ent = open(f'{D}/extant_nodes.Rev').read()
bt = []   # (k, parent node, child node or None)
for m in re.finditer(r'^branch_time\[(\d+)\] := abs\((age_n\d+)(?: - (age_n\d+))?\)$', ent, re.M):
    bt.append((int(m.group(1)), m.group(2)[4:], m.group(3)[4:] if m.group(3) else None))
nb = int(re.search(r'^n_extant_branches <- (\d+)', ent, re.M).group(1))
assert len(bt) == nb and set(age) >= {p for _, p, _ in bt}, (len(bt), nb)
dt = {k: age[p] - (age[c] if c else 0.0) for k, p, c in bt}
bad = [k for k, v in dt.items() if v <= 0]
if bad:
    print('WARNING non-positive branch times (median ages out of order):', bad, file=sys.stderr)
dt = {k: max(v, 0.01) for k, v in dt.items()}
child_of = {c: k for k, p, c in bt if c}            # node -> branch above it
parent_br = {k: child_of.get(p) for k, p, c in bt}  # None = a root branch
order, seen = [], set()
while len(order) < nb:
    for k, p, c in bt:
        if k not in seen and (parent_br[k] is None or parent_br[k] in seen):
            order.append(k); seen.add(k)

L = [f'# generated by clock_ss.py {S} {CLOCK} {TIMES} {SEED}', f'seed({SEED})', 'moves = VectorMoves()', 'monitors = VectorMonitors()',
     f'nuc <- readDiscreteCharacterData("{D}/aln.fasta")', f'topology <- readTrees("{D}/backbone.nwk", treetype="non-clock")[1]']
if not FREE:
    L += [f'branch_time[{k}] <- {dt[k]:.6f}' for k in sorted(dt)]
else:
    cl = {m.group(1): frozenset(re.findall(r'"([^"]+)"', m.group(2))) for m in re.finditer(r'^clade_(n\d+) = clade\((.*)\)$', ent, re.M)}
    root = max(cl, key=lambda k: len(cl[k]))
    def nwk(n):   # rooted time tree from the clades and the median ages
        kids = [k for k in cl if cl[k] < cl[n] and not any(cl[k] < cl[j] < cl[n] for j in cl)]
        tips = cl[n] - set().union(*(cl[k] for k in kids)) if kids else cl[n]
        parts = [f'{nwk(k)}:{age[n] - age[k]:.6f}' for k in kids] + [f'{t}:{age[n]:.6f}' for t in sorted(tips)]
        return '(' + ','.join(parts) + ')' + n
    open(OUT + '.start.nwk', 'w').write(nwk(root).replace(root, '', 1)[::-1].replace(root[::-1], '', 1)[::-1] + ';\n')
    txt = open(OUT + '.start.nwk').read(); txt = re.sub(r'\)n\d+', ')', txt); open(OUT + '.start.nwk', 'w').write(txt)
    mins = {}
    for r in csv.DictReader(open(f'{D}/constraints_members.tsv'), delimiter='\t'):
        mem = r['members'].split(','); E = frozenset(x for x in mem if not x.startswith('FOSSIL_')); F = [x for x in mem if x.startswith('FOSSIL_')]
        if not F or not E: continue
        crown = next((k for k in cl if cl[k] == E), None)
        if crown is None and len(E) > 1: continue
        up = [k for k in cl if (E < cl[k])]
        if not up: continue
        par = min(up, key=lambda k: len(cl[k]))
        if par == root: continue
        fmin = {t['taxon']: float(t['min_age']) for t in csv.DictReader(open(f'{D}/fbd_taxa.tsv'), delimiter='\t')}
        mins[par] = max(mins.get(par, 0.0), max(fmin[f] for f in F))
    L += [f'start_tree <- readTrees("{OUT}.start.nwk", treetype="clock")[1]', 'taxa <- start_tree.taxa()',
          'bd_lambda ~ dnExponential(10.0)', 'bd_mu ~ dnExponential(10.0)', 'bd_lambda.setValue(0.05)', 'bd_mu.setValue(0.02)',
          'moves.append( mvScale(bd_lambda, lambda=0.1, tune=TRUE, weight=3.0) )', 'moves.append( mvScale(bd_mu, lambda=0.1, tune=TRUE, weight=3.0) )',
          f'rho_bd <- {re.search(r"^rho <- *([0-9./ ]+)", open(f"{D}/settings.Rev").read(), re.M).group(1).split("#")[0].strip()}',
          f'bd = dnBDP(lambda=bd_lambda, mu=bd_mu, rho=rho_bd, rootAge={age[root]:.6f}, samplingStrategy="uniform", condition="survival", taxa=taxa)',
          'timetree ~ dnConstrainedTopology(bd, backbone=start_tree, initialTree=start_tree)',
          f'moves.append( mvNodeTimeSlideUniform(timetree, weight={nb}.0) )']
    L += [l.replace('fbd_tree', 'timetree') for l in ent.splitlines() if l.startswith(('clade_', 'age_', 'branch_time'))]
    for i, (n, mn) in enumerate(sorted(mins.items()), 1):
        L += [f'cal_w[{i}] ~ dnUniform(age_{n} - 10000.0, age_{n} - {mn:.4f})', f'cal_w[{i}].clamp(0.0)']
    print('free times: minimum-age calibrations', len(mins), file=sys.stderr)
L += ['clock_init <- 0.002', 'branch_rates_mean ~ dnExponential(10.0)', 'branch_rates_mean.setValue(clock_init)',
      'moves.append( mvScale(branch_rates_mean, lambda=0.1, tune=TRUE, weight=5.0) )']
if CLOCK == 'strict':
    L += [f'for (i in 1:{nb}) {{ branch_rates[i] := branch_rates_mean }}']
else:
    if CLOCK == 'ln':
        L += ['ln_sigma ~ dnExponential(1.0 / 0.587405)', 'ln_sigma.setValue(0.5)', 'moves.append( mvScale(ln_sigma, lambda=0.1, tune=TRUE, weight=5.0) )',
              'ln_mu := ln(branch_rates_mean) - 0.5 * ln_sigma * ln_sigma']
    if CLOCK == 'gam':
        L += ['gam_k ~ dnExponential(1.0)', 'gam_k.setValue(1.0)', 'moves.append( mvScale(gam_k, lambda=0.1, tune=TRUE, weight=5.0) )']
    if CLOCK == 'igr':
        L += ['igr_v ~ dnExponential(10.0)', 'igr_v.setValue(0.1)', 'moves.append( mvScale(igr_v, lambda=0.1, tune=TRUE, weight=5.0) )']
    if CLOCK == 'acln':
        L += ['ac_s ~ dnExponential(10.0)', 'ac_s.setValue(0.05)', 'moves.append( mvScale(ac_s, lambda=0.1, tune=TRUE, weight=5.0) )']
    for k in order:
        if CLOCK == 'exp':
            d = 'dnExp(1.0 / branch_rates_mean)'
        elif CLOCK == 'ln':
            d = 'dnLognormal(ln_mu, ln_sigma)'
        elif CLOCK == 'gam':
            d = 'dnGamma(gam_k, gam_k / branch_rates_mean)'
        elif CLOCK == 'igr':
            bk = f'(branch_time[{k}] + 0.01)' if FREE else f'branch_time[{k}]'
            d = f'dnGamma({bk} / igr_v, {bk} / (igr_v * branch_rates_mean))'
        elif CLOCK == 'acln':
            pr = 'branch_rates_mean' if parent_br[k] is None else f'branch_rates[{parent_br[k]}]'
            bk = f'(branch_time[{k}] + 0.01)' if FREE else f'branch_time[{k}]'
            L += [f'ac_mu[{k}] := ln({pr}) - 0.5 * ac_s * ac_s * {bk}', f'ac_sd[{k}] := ac_s * sqrt({bk})']
            d = f'dnLognormal(ac_mu[{k}], ac_sd[{k}])'
        else:
            sys.exit('unknown clock ' + CLOCK)
        L += [f'branch_rates[{k}] ~ {d}', f'branch_rates[{k}].setValue(clock_init)',
              f'moves.append( mvScale(branch_rates[{k}], lambda=0.1, tune=TRUE, weight=1.0) )']
    L += ['moves.append( mvVectorScale(branch_rates, lambda=0.1, tune=TRUE, weight=5.0) )']
L += [f'source("{D}/exact_brlens.Rev")', 'extant_phylo := fnTreeAssembly(topology, ext_bl)',
      'sf ~ dnDirichlet(v(1,1,1,1))', 'er ~ dnDirichlet(v(1,1,1,1,1,1))', 'alpha_nuc ~ dnExponential(1.0)', 'alpha_nuc.setValue(0.5)',
      'moves.append( mvSimplexElementScale(er, alpha=10.0, tune=TRUE, weight=5.0) )', 'moves.append( mvSimplexElementScale(sf, alpha=10.0, tune=TRUE, weight=5.0) )',
      'moves.append( mvScale(alpha_nuc, lambda=0.1, tune=TRUE, weight=2.0) )', 'Q_nuc := fnGTR(er, sf)', 'rates_nuc := fnDiscretizeGamma(alpha_nuc, alpha_nuc, 4)',
      'phySeq ~ dnPhyloCTMC(tree=extant_phylo, Q=Q_nuc, siteRates=rates_nuc, type="DNA")', 'phySeq.clamp(nuc)',
      'mymodel = model(branch_rates_mean)',
      'print("START lnProb tree", timetree.lnProbability())' if FREE else 'print("START fixed times")',
      'print("START lnLik", phySeq.lnProbability())',
      'pre <- out_prefix',
      'pow_p = powerPosterior(mymodel, moves, monitors, pre + ".pp", cats=n_cats, sampleFreq=10)',
      'pow_p.burnin(generations=n_burn, tuningInterval=200)',
      'pow_p.run(generations=n_gen)',
      'ss = steppingStoneSampler(file=pre + ".pp", powerColumnName="power", likelihoodColumnName="likelihood")',
      'ps = pathSampler(file=pre + ".pp", powerColumnName="power", likelihoodColumnName="likelihood")',
      f'write("{S}", "{CLOCK}", "{TIMES}", "{SEED}", ss.marginal(), ps.marginal(), "\\n", filename=pre + ".ml.tsv", separator="\\t")',
      'print("ML stepping-stone", ss.marginal(), "path", ps.marginal())', 'q()']
open(OUT, 'w').write('\n'.join(L) + '\n')
print(OUT, 'branches', nb, 'order ok', len(order) == nb)
