#!/usr/bin/env python3
"""Simulation study of ffbd at realistic size (user request, 11 Nov 2026; design after Heath et al. 2014 and Barido-Sottani et al. 2019).

One replicate = one fossilized birth-death tree simulated forward from a known root age with known lambda, mu, psi and rho, plus
  - fossil age windows that contain the true age (width 2-8 Myr, true age at a random position inside),
  - clade constraints built from the true tree (each fossil assigned to the total group of the extant clade it attaches to, or of
    its parent or grandparent clade, like a morphological placement of varying precision), always true for the true tree,
  - branch rates per extant branch ~ Exponential(mean M) (the ffbd clock prior), and two kinds of branch-length data:
      arm "exact": b_obs ~ Normal(rate x time, sqrt(b/L)) per unrooted edge, i.e. data generated by the ffbd model itself;
      arm "dna"  : (on OSCER, sim_study_rep.sh) DNA simulated on the true phylogram (IQ-TREE AliSim, GTR+G4, L sites), ML branch
                   lengths on the true topology and bootstrap SEs, exactly as for the real fish clades (fast_fbd_test/scripts/fish_fast.py).
The truth (node ages, fossil ages, rates, sampled-ancestor count) goes to truth.tsv; sim_study_summary.py scores coverage and error.

  sim_study.py sbc OUTDIR SEED           -> same files; parameters drawn from the ffbd priors (simulation-based calibration, exact arm only)
  sim_study.py simulate OUTDIR SEED      -> OUTDIR/{fbd_taxa.tsv,settings.Rev,backbone.nwk,initial.nwk,constraints_members.tsv,
                                             extant_nodes.Rev,fast_terms_exact.Rev,phylo_subs.nwk,truth.tsv}
Standard library only (runs on OSCER without modules).
"""
import math, os, random, sys

T, LAM, MU, PSI, RHO = 100.0, 0.10, 0.06, 0.01, 0.5    # scenario S1 (about 55 extant tips and 25 fossils)
M_RATE, L_SITES = 0.004, 2000                             # mean clock rate (subs/site/Myr) and alignment length
N_MIN, N_MAX, F_MIN = 30, 120, 5
SBC = False          # 'sbc' command: parameters drawn from the ffbd priors, no size filter, exact constraints and windows (see simulate_sbc)
SBC_ROOT = (30.0, 2.0)   # root prior Normal(mean, sd) used in the sbc mode (analysis: --root-prior normal 30 2)
SBC_SE = 0.01            # constant observation SD in the sbc mode (an SE computed from the true branch length would leak the truth)


class Lin:
    __slots__ = ('start', 'end', 'kind', 'kids', 'fossils')

    def __init__(self, start):
        self.start, self.end, self.kind, self.kids, self.fossils = start, None, None, [], []


def forward(rng):
    """two lineages from the root at age T; returns them (each lineage: fossils, end event, children)"""
    roots = [Lin(T), Lin(T)]
    stack = list(roots)
    tot = LAM + MU + PSI
    n = 0
    while stack:
        L = stack.pop()
        a = L.start
        while True:
            a -= rng.expovariate(tot)
            if a <= 0:
                L.end, L.kind = 0.0, 'present'
                break
            u = rng.random() * tot
            if u < PSI:
                L.fossils.append(a)
                continue
            L.end = a
            if u < PSI + LAM:
                L.kind = 'split'
                L.kids = [Lin(a), Lin(a)]
                stack += L.kids
                n += 1
                if n > 20000:
                    return None
            else:
                L.kind = 'death'
            break
    return roots


class Node:
    __slots__ = ('age', 'ch', 'name', 'parent', 'extant')

    def __init__(self, age, ch=(), name=None):
        self.age, self.ch, self.name, self.parent = age, list(ch), name, None
        for c in self.ch:
            c.parent = self


def reconstruct(L, rng, names):
    if L.kind == 'split':
        subs = [s for s in (reconstruct(k, rng, names) for k in L.kids) if s is not None]
        sub = Node(L.end, subs) if len(subs) == 2 else (subs[0] if subs else None)
    elif L.kind == 'present' and rng.random() < RHO:
        names['e'] += 1
        sub = Node(0.0, name=f"t{names['e']:03d}")
    else:
        sub = None
    for f in sorted(L.fossils):             # youngest first, walking up the lineage
        names['f'] += 1
        tip = Node(f, name=f"FOSSIL_f{names['f']:03d}")
        sub = tip if sub is None else Node(f, [sub, tip])   # fossil with sampled descendants: a sampled ancestor (zero pendant)
    return sub


def tips(n):
    return [n] if not n.ch else [t for c in n.ch for t in tips(c)]


def nwk(n, parent_age):
    bl = parent_age - n.age
    if not n.ch:
        return f'{n.name}:{bl:.10f}'
    return '(' + ','.join(nwk(c, n.age) for c in n.ch) + f'):{bl:.10f}'


def draw_prior(rng):
    """sbc mode: lambda, mu, psi ~ Exponential(rate 10), mean clock rate ~ Exponential(rate 10), root ~ Normal(30, 2): the ffbd priors"""
    global T, LAM, MU, PSI, M_RATE
    T = -1.0
    while T <= 0:
        T = rng.gauss(*SBC_ROOT)
    LAM, MU, PSI, M_RATE = (rng.expovariate(10.0) for _ in range(4))


def simulate(out, seed):
    rng = random.Random(seed)
    for attempt in range(1, 100001):
        if SBC:
            draw_prior(rng)   # every attempt redraws the parameters: accepted pairs follow prior x tree density (condition = time)
        roots = forward(rng)
        if roots is None:
            continue
        names = {'e': 0, 'f': 0}
        subs = [reconstruct(r, rng, names) for r in roots]
        if any(s is None for s in subs):
            continue
        root = Node(T, subs)
        ext = [t for t in tips(root) if not t.name.startswith('FOSSIL')]
        fos = [t for t in tips(root) if t.name.startswith('FOSSIL')]
        if not all(any(not t.name.startswith('FOSSIL') for t in tips(s)) for s in subs):
            continue
        if SBC or (N_MIN <= len(ext) <= N_MAX and F_MIN <= len(fos)):
            break
    else:
        sys.exit('no tree accepted')
    os.makedirs(out, exist_ok=True)
    for n in [root] + [x for x in iter_nodes(root)]:
        n.extant = frozenset(t.name for t in tips(n) if not t.name.startswith('FOSSIL'))
    allE = frozenset(t.name for t in ext)

    # extant tree (fossils pruned): one node per extant clade
    def prune(n):
        if not n.ch:
            return None if n.name.startswith('FOSSIL') else Node(0.0, name=n.name)
        k = [s for s in (prune(c) for c in n.ch) if s is not None]
        return Node(n.age, k) if len(k) == 2 else (k[0] if k else None)
    ext_tree = prune(root)
    assert abs(ext_tree.age - T) < 1e-9 and len(tips(ext_tree)) == len(ext)
    ext_nodes = {}          # extant clade -> node of the extant tree
    def idx(n):
        ext_nodes[frozenset(t.name for t in tips(n))] = n
        for c in n.ch:
            idx(c)
    idx(ext_tree)
    parent_of = {}
    for cl, n in ext_nodes.items():
        if n.parent is not None:
            parent_of[cl] = frozenset(t.name for t in tips(n.parent))

    # fossil windows
    win = {}
    for f in fos:
        if SBC:     # fixed 4-Myr grid of stages: the window depends on the age only through its bin, so the uniform window term is exact
            k = math.floor(f.age / 4.0)
            win[f.name] = (4.0 * k, 4.0 * k + 4.0)
            continue
        w = rng.uniform(2.0, 8.0)
        lo = max(0.01, f.age - rng.random() * w)
        hi = min(T - 0.01, lo + w)
        lo = min(lo, f.age)
        win[f.name] = (lo, hi)
        assert lo <= f.age <= hi

    # constraints: fossil -> extant clade it attaches to (S), coarsened 0/1/2 levels, then the true clade of that group
    assign = {}
    for f in fos:
        if SBC:     # side of the root only: a constraint that is exactly the set of trees it is computed from (no information leak)
            x = f
            while x.parent is not root:
                x = x.parent
            assign.setdefault(x.extant, []).append(f)
            continue
        x = f
        while not x.extant:
            x = x.parent
        S = x.extant
        k = rng.choices([0, 1, 2], [0.5, 0.25, 0.25])[0]
        for _ in range(k):
            P = parent_of.get(S)
            if P is None or P == allE:
                break
            S = P
        assign.setdefault(S, []).append(f)
    cons = {}
    for S, fl in assign.items():
        want = set(S) | {f.name for f in fl}
        y = fl[0]
        while not want <= {t.name for t in tips(y)}:
            y = y.parent
        assert y is not root
        mem = frozenset(t.name for t in tips(y))
        cons.setdefault(mem, len(cons) + 1)
    with open(f'{out}/constraints_members.tsv', 'w') as fh:
        fh.write('constraint\tcal_ids\tn_extant\tn_fossils\tmembers\n')
        for mem, k in sorted(cons.items(), key=lambda z: z[1]):
            ne = sum(not m.startswith('FOSSIL') for m in mem)
            fh.write(f'cl_S{k}\tS{k}\t{ne}\t{len(mem) - ne}\t{",".join(sorted(mem))}\n')

    # taxa, settings, trees
    with open(f'{out}/fbd_taxa.tsv', 'w') as fh:
        fh.write('taxon\tmax_age\tmin_age\n')
        for t in sorted(ext, key=lambda z: z.name):
            fh.write(f'{t.name}\t0\t0\n')
        for f in sorted(fos, key=lambda z: z.name):
            fh.write(f'{f.name}\t{win[f.name][1]:.6f}\t{win[f.name][0]:.6f}\n')
    open(f'{out}/settings.Rev', 'w').write(f'# simulated replicate (ffbd/scripts/sim_study.py, seed {seed})\nroot_age_init <- {T}\n'
                                           f'clock_rate_init <- {M_RATE}\nrho <- {RHO}\ncond <- "root"\nroot_mean <- {SBC_ROOT[0] if SBC else T}\nroot_sd <- {SBC_ROOT[1] if SBC else 5.0}\n')
    open(f'{out}/initial.nwk', 'w').write('(' + ','.join(nwk(c, root.age) for c in root.ch) + ');\n')
    open(f'{out}/backbone.nwk', 'w').write('(' + ','.join(nwk(c, ext_tree.age) for c in ext_tree.ch) + ');\n')

    # extant nodes and branches, same naming and order as fish_fast.py "table" (nodes sorted by size then names; branches pre-order)
    branches = []
    def walk(nd):
        for c in nd.ch:
            branches.append((c, nd))
            walk(c)
    walk(ext_tree)
    allset = frozenset(t.name for t in tips(ext_tree))
    ref = sorted(allset)[0]
    cl = lambda n: frozenset(t.name for t in tips(n))
    nodes = sorted({cl(p) for c, p in branches}, key=lambda c: (len(c), sorted(c)))
    nm = {c: f'n{i}' for i, c in enumerate(nodes, 1)}
    L1 = ['# generated by ffbd/scripts/sim_study.py (fish_fast.py naming): extant node clades and branch times']
    for c in nodes:
        q = ', '.join(f'"{t}"' for t in sorted(c))
        L1 += [f'clade_{nm[c]} = clade({q})', f'age_{nm[c]} := tmrca(fbd_tree, clade_{nm[c]})']
    for i, (c, p) in enumerate(branches, 1):
        L1.append(f'branch_time[{i}] := abs(age_{nm[cl(p)]})' if not c.ch else f'branch_time[{i}] := abs(age_{nm[cl(p)]} - age_{nm[cl(c)]})')
    L1.append(f'n_extant_branches <- {len(branches)}')
    open(f'{out}/extant_nodes.Rev', 'w').write('\n'.join(L1) + '\n')
    rates = [rng.expovariate(1.0 / M_RATE) for _ in branches]
    subs = {}
    edge_ids = {}
    for i, (c, p) in enumerate(branches, 1):
        s = cl(c)
        key = s if ref not in s else allset - s
        edge_ids.setdefault(key, []).append(i)
        subs[id(c)] = rates[i - 1] * (p.age - c.age)
    L2 = ['# generated by ffbd/scripts/sim_study.py: exact-model observations b_obs ~ Normal(rate x time, sqrt(b/L)), floor 1/L']
    keys = sorted(edge_ids, key=lambda k: (len(k), sorted(k)))
    for j, k in enumerate(keys, 1):
        ids = edge_ids[k]
        b = sum(rates[i - 1] * (branches[i - 1][1].age - branches[i - 1][0].age) for i in ids)
        se = SBC_SE if SBC else max(math.sqrt(b / L_SITES), 1.0 / L_SITES)
        obs = rng.gauss(b, se) if SBC else abs(rng.gauss(b, se))
        mu = ' + '.join(f'branch_rates[{i}] * branch_time[{i}]' for i in ids)
        L2 += [f'b_mu[{j}] := abs({mu})', f'b_obs[{j}] ~ dnNormal(b_mu[{j}], {se:.8f})', f'b_obs[{j}].clamp({obs:.8f})']
    open(f'{out}/fast_terms_exact.Rev', 'w').write('\n'.join(L2) + '\n')

    def pnwk(n):
        if not n.ch:
            return f'{n.name}:{subs[id(n)]:.10f}'
        return '(' + ','.join(pnwk(c) for c in n.ch) + f'):{subs.get(id(n), 0.0):.10f}'
    open(f'{out}/phylo_subs.nwk', 'w').write('(' + ','.join(pnwk(c) for c in ext_tree.ch) + ');\n')

    nsa = sum(1 for f in fos if f.parent is not None and f.parent.age == f.age)
    with open(f'{out}/truth.tsv', 'w') as fh:
        fh.write('param\ttrue\n')
        for k, v in [('root', T), ('speciation_rate', LAM), ('extinction_rate', MU), ('psi', PSI), ('num_samp_anc', nsa),
                     ('branch_rates_mean', M_RATE), ('n_extant', len(ext)), ('n_fossils', len(fos)), ('n_constraints', len(cons)),
                     ('attempts', attempt)]:
            fh.write(f'{k}\t{v}\n')
        for c in nodes:
            fh.write(f'age_{nm[c]}\t{ext_nodes[c].age:.8f}\n')
        for f in sorted(fos, key=lambda z: z.name):
            fh.write(f'{f.name}\t{f.age:.8f}\n')
        if SBC:     # nodes and a fossil chosen without looking at ages, for rank tests: the MRCA of each root side, one random fossil
            for k, c in enumerate(ext_tree.ch, 1):
                if c.ch:
                    fh.write(f'sbc_side{k}\tage_{nm[cl(c)]}\n')
            if fos:
                fh.write(f'sbc_fossil\tage_{rng.choice(fos).name}\n')
    print(f'seed {seed}: extant {len(ext)} fossils {len(fos)} sampled ancestors {nsa} constraints {len(cons)} attempts {attempt}')


def iter_nodes(n):
    for c in n.ch:
        yield c
        yield from iter_nodes(c)


if __name__ == '__main__':
    if sys.argv[1] == 'simulate':
        simulate(sys.argv[2], int(sys.argv[3]))
    elif sys.argv[1] == 'sbc':
        SBC = True
        simulate(sys.argv[2], int(sys.argv[3]))
    else:
        sys.exit(__doc__)
