#!/usr/bin/env python3
"""Three-program check of the sampled-ancestor tree prior (user request, 11 Nov 2026).

Same model in ffbd, MrBayes 3.2.7 and RevBayes 1.3.2: A06 or A12 extant tree held fixed, fossils free inside their clade constraints and
age windows, lambda, mu, psi and the root age FIXED, no sequence data. With every rate fixed the conditioning constants (root, survival)
drop out, so the three programs must give the same distribution of node ages, fossil placements and sampled-ancestor counts. RevBayes's
collapse-expand move is the suspected cause of the ffbd/RevBayes difference (VALIDATION.md, Step 3); MrBayes is the independent referee.
(BEAST2's SA package is not used: its monophyly constraints count fossils as clade members, so it cannot hold an extant backbone fixed
while fossils move freely; MrBayes partial constraints can.)

  make_fixed3.py OUTDIR      (run from FBD/tree)  -> OUTDIR/{SET}_fixed.txt, {SET}_mb.nex, {SET}_rb.cfg.Rev, fbd_fixed.Rev
"""
import csv, os, re, subprocess, sys

OUT = sys.argv[1]
os.makedirs(OUT, exist_ok=True)
LAM, MU, PSI = 0.10, 0.04, 0.03          # fixed values, same for both sets (chosen so sampled ancestors are common)
ROOT = {'A06': 73.5, 'A12': 139.2}       # root_age_init of each set (= the start tree's root age)
RB_REMOTE = os.environ.get('RB_REMOTE', 'data')   # folder holding the A06/A12 data sets on the machine that runs RevBayes
VAL_REMOTE = os.environ.get('VAL_REMOTE', 'val3')   # output folder on that machine


def newick_clades(s):
    """extant clades (frozensets of tip names) of a newick string"""
    s = re.sub(r':[-0-9.eE+]+', '', s.strip().rstrip(';'))
    stack, out = [[]], []
    tok = re.findall(r'\(|\)|,|[^(),]+', s)
    for t in tok:
        if t == '(':
            stack.append([])
        elif t == ')':
            c = stack.pop()
            fs = frozenset(x for y in c for x in (y if isinstance(y, frozenset) else [y]))
            out.append(fs)
            stack[-1].append(fs)
        elif t != ',':
            stack[-1].append(t.strip())
    return out


# RevBayes script with fixed FBD rates and root: derived from fbd_run_root.Rev by text replacement (asserted below)
rev = open('fast_fbd_test/rev/fbd_run_root.Rev').read()
a = rev.index('speciation_rate ~ dnExponential(10)')
b = rev.index('moves.append( mv_ud )') + len('moves.append( mv_ud )')
rev = rev[:a] + f'speciation_rate <- {LAM}\nextinction_rate <- {MU}\npsi <- {PSI}' + rev[b:]
a = rev.index('    root_time_real ~ dnNormal')
b = rev.index('    cond_age := abs(root_time_real)') + len('    cond_age := abs(root_time_real)')
rev = rev[:a] + '    cond_age <- root_age_init   # FIXED root (make_fixed3.py)' + rev[b:]
assert 'root_time_real' not in rev and 'dnExponential(10)\n' not in rev.split('# ---- clock')[0]
open(f'{OUT}/fbd_fixed.Rev', 'w').write('# GENERATED by ffbd/scripts/make_fixed3.py from fast_fbd_test/rev/fbd_run_root.Rev: lambda, mu, psi and root fixed\n' + rev)

for S in ('A06', 'A12'):
    d = f'fast_fbd_test/fish_root/data/{S}_root'
    # ffbd: control input with the fixed values as start values; run with --fix-fbd --mode control
    subprocess.run(['python3', 'ffbd/scripts/ffbd_convert.py', '--set', d, '--out', f'{OUT}/{S}_fixed.txt', '--mode', 'control'],
                   check=True, stdout=subprocess.DEVNULL)
    t = open(f'{OUT}/{S}_fixed.txt').read()
    t = re.sub(r'^init_lambda .*$', f'init_lambda {LAM}', t, flags=re.M)
    t = re.sub(r'^init_mu .*$', f'init_mu {MU}', t, flags=re.M)
    t = re.sub(r'^init_psi .*$', f'init_psi {PSI}', t, flags=re.M)
    assert re.search(r'^init_cond_age ([0-9.]+)', t, re.M) and abs(float(re.search(r'^init_cond_age ([0-9.]+)', t, re.M).group(1)) - ROOT[S]) < 1e-6
    open(f'{OUT}/{S}_fixed.txt', 'w').write(t)
    rho = float(re.search(r'^rho (\S+)', t, re.M).group(1))

    # RevBayes cfg
    open(f'{OUT}/{S}_rb.cfg.Rev', 'w').write('\n'.join([
        'mode <- "control"', f'data_dir <- "{RB_REMOTE}/{S}_root"', 'aln_file <- "none"', f'fast_dir <- "{RB_REMOTE}/{S}_root"',
        f'out_prefix <- "{VAL_REMOTE}/OUTPREFIX"', 'seed_val <- SEED', 'n_gen <- 300000', 'n_burn <- 2000', 'printgen <- 20', 'treegen <- 100',
        'ckpt_gen <- 10000', 'under_prior <- FALSE', 'log_rates <- FALSE', 'start_only <- FALSE', f'source("{VAL_REMOTE}/fbd_fixed.Rev")', '']))

    # MrBayes
    taxa = list(csv.DictReader(open(f'{d}/fbd_taxa.tsv'), delimiter='\t'))
    ext = [r['taxon'] for r in taxa if float(r['max_age']) == 0]
    fos = [r for r in taxa if float(r['max_age']) > 0]
    assert all(float(r['min_age']) < ROOT[S] for r in fos)
    cons = [(r['constraint'], r['members'].split(',')) for r in csv.DictReader(open(f'{d}/constraints_members.tsv'), delimiter='\t')]
    bb = [c for c in newick_clades(open(f'{d}/backbone.nwk').read()) if 1 < len(c) < len(ext)]
    assert set().union(*bb) <= set(ext)
    L = ['#NEXUS', 'begin data;', f'  dimensions ntax={len(taxa)} nchar=1;', '  format datatype=dna missing=? gap=-;', '  matrix']
    L += [f'    {r["taxon"]} {"?" if float(r["max_age"]) > 0 else "A"}' for r in taxa]
    L += ['  ;', 'end;', '', 'begin mrbayes;', '  set autoclose=yes nowarn=yes seed=SEED swapseed=SEED;', '  lset nst=1 rates=equal;']
    for r in fos:
        L.append(f'  calibrate {r["taxon"]} = uniform({float(r["min_age"]):g},{float(r["max_age"]):g});')
    names = []
    for k, (nm, mem) in enumerate(cons):
        L.append(f'  constraint {nm} hard = {" ".join(mem)};'); names.append(nm)
    for k, c in enumerate(bb):
        L.append(f'  constraint bb{k + 1} partial = {" ".join(sorted(c))} : {" ".join(sorted(set(ext) - c))};'); names.append(f'bb{k + 1}')
    L += [f'  prset topologypr = constraints({",".join(names)});',
          '  prset brlenspr = clock:fossilization;',
          f'  prset speciationpr = fixed({LAM - MU:.10g});        [lambda - mu]',
          f'  prset extinctionpr = fixed({MU / LAM:.10g});        [mu / lambda]',
          f'  prset fossilizationpr = fixed({PSI / (MU + PSI):.10g});  [psi / (mu + psi)]',
          f'  prset sampleprob = {rho:.10g};', '  prset samplestrat = random;',
          f'  prset treeagepr = fixed({ROOT[S]:g});', '  prset nodeagepr = calibrated;', '  prset clockratepr = fixed(1.0);',
          '  mcmcp data=no ngen=20000000 samplefreq=1000 printfreq=1000000 nruns=1 nchains=1 diagnfreq=1000000 filename=OUTPREFIX;',
          '  mcmc;', 'end;', '']
    open(f'{OUT}/{S}_mb.nex', 'w').write('\n'.join(L))
    print(S, 'extant', len(ext), 'fossils', len(fos), 'hard constraints', len(cons), 'backbone partial constraints', len(bb), 'rho', round(rho, 5))
