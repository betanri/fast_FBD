#!/usr/bin/env python3
# FAST FBD inputs for a fish pilot clade: unrooted fixed tree, bootstrap alignments, branch table and Rev terms.
#   fish_fast.py prep  ALN.fasta BACKBONE.nwk OUTDIR BOOTDIR N SEED     -> OUTDIR/unrooted.nwk, BOOTDIR/bNNNN.fa
#   fish_fast.py table ALN.fasta BACKBONE.nwk ML.treefile BOOTDIR OUTDIR -> OUTDIR/{extant_nodes.Rev,fast_terms.Rev,branch_table.tsv,clades.tsv}
# Same method as the bears: GTR+G4 ML branch lengths on the fixed topology (IQ-TREE -te); SE = SD over site-resampled
# bootstrap replicates, each re-estimated on the fixed topology; the two root branches form one observed unrooted edge;
# SE floor = 1/L (one substitution over the alignment).
import sys, re, glob, random, statistics, pathlib

def parse(s):
    s = s.strip().rstrip(";")
    i = 0
    def node():
        nonlocal i
        n = {"ch": [], "name": None, "len": 0.0}
        if s[i] == "(":
            i += 1
            while True:
                n["ch"].append(node())
                if s[i] == ",": i += 1; continue
                if s[i] == ")": i += 1; break
                raise ValueError(s[i:i + 30])
        m = re.match(r"[^,():;\[]+", s[i:])
        if m:
            if not n["ch"]: n["name"] = m.group(0)
            i += len(m.group(0))
        if i < len(s) and s[i] == "[":
            i = s.index("]", i) + 1
        if i < len(s) and s[i] == ":":
            i += 1
            m = re.match(r"[-0-9.eE+]+", s[i:]); n["len"] = float(m.group(0)); i += len(m.group(0))
        if i < len(s) and s[i] == "[":
            i = s.index("]", i) + 1
        return n
    return node()

def tips(n):
    return [n["name"]] if not n["ch"] else [t for c in n["ch"] for t in tips(c)]

def read_fasta(p):
    d = {}
    for b in open(p).read().split(">")[1:]:
        n, s = b.split("\n", 1); d[n.split()[0]] = s.replace("\n", "")
    return d

def nwk(n):
    return n["name"] + f":{n['len']:g}" if not n["ch"] else "(" + ",".join(nwk(c) for c in n["ch"]) + ")" + f":{n['len']:g}"

def unroot(t):
    """Newick text with the root bifurcation collapsed into a trifurcation (IQ-TREE -te input)"""
    assert len(t["ch"]) == 2
    a, b = t["ch"]
    if not b["ch"]: a, b = b, a        # b must be internal so its children can move up
    assert b["ch"], "both root children are tips"
    a2 = dict(a); a2["len"] = a["len"] + b["len"]
    return "(" + ",".join([nwk(a2)] + [nwk(c) for c in b["ch"]]) + ");\n"

def edges(t, ref, all_t):
    d = {}
    def rec(n):
        for c in n["ch"]:
            side = frozenset(tips(c)); key = side if ref not in side else all_t - side
            d[key] = d.get(key, 0.0) + c["len"]
            rec(c)
    rec(t)
    return d

cmd = sys.argv[1]
if cmd == "prep":
    aln, bb, out, bootd, N, seed = sys.argv[2:8]
    out = pathlib.Path(out); bootd = pathlib.Path(bootd); out.mkdir(parents=True, exist_ok=True); bootd.mkdir(parents=True, exist_ok=True)
    seqs = read_fasta(aln); L = {len(v) for v in seqs.values()}; assert len(L) == 1; L = L.pop()
    t = parse(open(bb).read())
    assert set(tips(t)) == set(seqs), "backbone and alignment taxa differ"
    (out / "unrooted.nwk").write_text(unroot(t))
    random.seed(int(seed)); names = list(seqs)
    for i in range(1, int(N) + 1):
        idx = [random.randrange(L) for _ in range(L)]
        with open(bootd / f"b{i:04d}.fa", "w") as f:
            for k in names: f.write(f">{k}\n{''.join(seqs[k][j] for j in idx)}\n")
    print("prep ok: taxa", len(names), "sites", L, "replicates", N)
elif cmd == "table":
    aln, bb, mlf, bootd, out = sys.argv[2:7]
    out = pathlib.Path(out); out.mkdir(parents=True, exist_ok=True)
    seqs = read_fasta(aln); L = len(next(iter(seqs.values())))
    rooted = parse(open(bb).read())
    all_t = frozenset(tips(rooted)); ref = sorted(all_t)[0]; n = len(all_t)
    ml = parse(open(mlf).read())
    assert frozenset(tips(ml)) == all_t
    ml_e = edges(ml, ref, all_t)
    assert len(ml_e) == 2 * n - 3, (len(ml_e), n)
    boots = []
    for f in sorted(glob.glob(str(pathlib.Path(bootd) / "*.treefile"))):
        e = edges(parse(open(f).read()), ref, all_t)
        assert set(e) == set(ml_e), f
        boots.append(e)
    floor = 1.0 / L
    branches = []
    def walk(nd):
        for c in nd["ch"]:
            cl = frozenset(tips(c))
            branches.append({"child": cl, "parent": frozenset(tips(nd)), "tip": c["name"], "edge": cl if ref not in cl else all_t - cl})
            walk(c)
    walk(rooted)
    assert len(branches) == 2 * n - 2 and all(len(x["ch"]) in (0, 2) for x in [rooted]), len(branches)
    nodes = sorted({b["parent"] for b in branches}, key=lambda c: (len(c), sorted(c)))
    assert len(nodes) == n - 1, (len(nodes), n)
    names = {c: f"n{i}" for i, c in enumerate(nodes, 1)}
    L1 = ["# generated by scripts/fish_fast.py: extant node clades and branch times (tips are at age 0)"]
    clades = ["node\tn_tips\ttips"]
    for c in nodes:
        q = ", ".join(f'"{t}"' for t in sorted(c))
        L1 += [f"clade_{names[c]} = clade({q})", f"age_{names[c]} := tmrca(fbd_tree, clade_{names[c]})"]
        clades.append(f"{names[c]}\t{len(c)}\t{','.join(sorted(c))}")
    for i, b in enumerate(branches, 1):
        pa = f"age_{names[b['parent']]}"
        L1.append(f"branch_time[{i}] := abs({pa})" if b["tip"] else f"branch_time[{i}] := abs({pa} - age_{names[b['child']]})")
    L1.append(f"n_extant_branches <- {len(branches)}")
    L2 = ["# generated by scripts/fish_fast.py: FAST observations, one per unrooted edge (the two root branches share one)"]
    tbl = ["term\tn_side_taxa\tb_ml\tboot_sd\tse_used\tboot_mean\tn_rooted_branches\trooted_branches\tfloor_used"]
    keys = sorted(ml_e, key=lambda k: (len(k), sorted(k)))
    nfl = 0
    for j, k in enumerate(keys, 1):
        vals = [b[k] for b in boots]; sd = statistics.stdev(vals); se = max(sd, floor); nfl += se > sd
        ids = [i for i, b in enumerate(branches, 1) if b["edge"] == k]
        mu = " + ".join(f"branch_rates[{i}] * branch_time[{i}]" for i in ids)
        L2 += [f"b_mu[{j}] := abs({mu})", f"b_obs[{j}] ~ dnNormal(b_mu[{j}], {se:.8f})", f"b_obs[{j}].clamp({ml_e[k]:.8f})"]
        tbl.append(f"{j}\t{len(k)}\t{ml_e[k]:.6f}\t{sd:.6f}\t{se:.6f}\t{statistics.mean(vals):.6f}\t{len(ids)}\t{','.join(map(str, ids))}\t{se > sd}")
    (out / "extant_nodes.Rev").write_text("\n".join(L1) + "\n")
    (out / "fast_terms.Rev").write_text("\n".join(L2) + "\n")
    (out / "branch_table.tsv").write_text("\n".join(tbl) + "\n")
    (out / "clades.tsv").write_text("\n".join(clades) + "\n")
    print(f"table ok: taxa {n}, rooted branches {len(branches)}, edges {len(keys)}, bootstraps {len(boots)}, floor {floor:.2e} used on {nfl} edges")
else:
    sys.exit("unknown command")
